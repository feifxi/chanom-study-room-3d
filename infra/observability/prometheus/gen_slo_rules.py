#!/usr/bin/env python3
"""
Generates rules/slo.yml: error-ratio recording rules for each SLO over every window, plus
multi-window, multi-burn-rate alerts (Google SRE Workbook, "Alerting on SLOs").
Edit the SLOS table, then run:  python3 infra/observability/prometheus/gen_slo_rules.py
"""
from pathlib import Path

API = 'route!~"/metrics|/health"'
SLOS = [
    {
        "name": "api_availability",
        "title": "API availability",
        "objective": 0.995,
        "desc": "99.5% of API requests (rooms list, stats, leaderboard, feedback, admin) don't fail with a 5xx",
        # Colyseus matchmaking is served outside express, so it isn't in these metrics; joins are covered by session_stability
        # `or vector(0)`: with no 5xx series at all, sum() returns nothing instead of 0
        "bad": f'(sum(rate(study_http_requests_total{{{API},code=~"5.."}}[{{w}}])) or vector(0))',
        "total": f"sum(rate(study_http_requests_total{{{{{API}}}}}[{{w}}]))",
    },
    {
        "name": "api_latency",
        "title": "API latency",
        "objective": 0.99,
        "desc": "99% of API requests finish within 300 ms",
        "bad": f'(sum(rate(study_http_request_duration_seconds_count{{{API}}}[{{w}}])) - sum(rate(study_http_request_duration_seconds_bucket{{{API},le="0.3"}}[{{w}}])))',
        "total": f"sum(rate(study_http_request_duration_seconds_count{{{{{API}}}}}[{{w}}]))",
    },
    {
        "name": "session_stability",
        "title": "Session stability",
        "objective": 0.99,
        "desc": "99% of room sessions don't end because the connection was lost for good",
        "bad": '(sum(rate(study_disconnects_total{{kind="timed_out"}}[{w}])) or vector(0))',
        "total": "sum(rate(study_joins_total[{w}]))",
    },
]
WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"]
# (severity, burn rate, long window, short window): page within minutes, ticket within hours
BURNS = [("page", 14.4, "1h", "5m"), ("page", 6, "6h", "30m"), ("ticket", 3, "1d", "2h"), ("ticket", 1, "3d", "6h")]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = ["# GENERATED by gen_slo_rules.py - edit that file, not this one.", "groups:"]
for slo in SLOS:
    n, budget = slo["name"], round(1 - slo["objective"], 6)
    out += [f"  - name: slo-{n}", "    rules:"]
    for w in WINDOWS:
        bad = slo["bad"].replace("{w}", w).replace("{{", "{").replace("}}", "}")
        total = slo["total"].replace("{w}", w).replace("{{", "{").replace("}}", "}")
        out += [f"      - record: slo:{n}:error_ratio_rate{w}", f"        expr: {q(f'({bad}) / ({total})')}"]
    out += [f"      - record: slo:{n}:objective", f"        expr: {q(str(slo['objective']))}"]
    for severity in ("page", "ticket"):
        pairs = [b for b in BURNS if b[0] == severity]
        expr = " or ".join(
            f"(slo:{n}:error_ratio_rate{long} > ({rate} * {budget}) and slo:{n}:error_ratio_rate{short} > ({rate} * {budget}))"
            for _, rate, long, short in pairs
        )
        speed = "Fast" if severity == "page" else "Slow"
        out += [
            f"      - alert: {''.join(p.title() for p in n.split('_'))}{speed}Burn",
            f"        expr: {q(expr)}",
            "        labels:",
            f"          severity: {severity}",
            f"          slo: {n}",
            "        annotations:",
            f"          summary: {q(slo['title'] + ' SLO is burning its error budget ' + ('fast' if severity == 'page' else 'slowly'))}",
            f"          description: {q('SLO: ' + slo['desc'] + '. Current 1h error ratio: {{ $value | humanizePercentage }}.')}",
            f"          runbook_url: {q('infra/observability/README.md#' + n.replace('_', '-'))}",
        ]

out += [
    "  - name: service-health",
    "    rules:",
    "      - alert: GameServerDown",
    '        expr: "up{job=\\"game\\"} == 0"',
    "        for: 1m",
    "        labels:",
    "          severity: page",
    "        annotations:",
    '          summary: "The game server is not answering /metrics"',
    '          runbook_url: "infra/observability/README.md#game-server-down"',
    "      - alert: EventLoopLagHigh",
    '        expr: "study_game_nodejs_eventloop_lag_p99_seconds > 0.1"',
    "        for: 5m",
    "        labels:",
    "          severity: ticket",
    "        annotations:",
    '          summary: "Game server event loop p99 lag is above 100 ms (players feel this as rubber-banding)"',
    '          runbook_url: "infra/observability/README.md#event-loop-lag"',
]
Path(__file__).with_name("rules").joinpath("slo.yml").write_text("\n".join(out) + "\n")
print("wrote rules/slo.yml")
